export const normalizePlateStr = (p: string): string => {
  return p.toUpperCase().replace(/[^A-Z0-9]/g, "");
};

export const getDriversByPlate = (plate: string): DriverLink[] => {
  const norm = normalizePlateStr(plate);
  if (!norm) return [];
  return DRIVERS_DATA.filter(d => normalizePlateStr(d.plate) === norm);
};

export const getAllPlatesWithDrivers = (): string[] => {
  const plates = DRIVERS_DATA.map(d => d.plate).filter(p => p !== "-");
  return Array.from(new Set(plates));
};
